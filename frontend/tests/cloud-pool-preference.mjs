import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { readCloudPoolPreference, saveCloudPoolPreference, readCloudChannelPreference, saveCloudChannelPreference, workspaceParameters } from '../src/cloudPoolPreference.js'

const values = new Map()
const storage = { getItem: key => values.get(key), setItem: (key, value) => values.set(key, value) }
assert.equal(readCloudChannelPreference(storage), 'ican')
assert.equal(readCloudChannelPreference({getItem(){throw Error('blocked')}}), 'ican')
saveCloudChannelPreference('ican', storage)
assert.equal(readCloudChannelPreference(storage), 'ican')
const oldProject = workspaceParameters({method:'running'})
assert.equal(oldProject.method, 'running')
assert.equal(readCloudChannelPreference(storage), 'ican')
saveCloudChannelPreference('invalid', storage)
assert.equal(readCloudChannelPreference(storage), 'ican')
saveCloudPoolPreference(false, storage)
assert.equal(readCloudChannelPreference(storage), 'ican')
saveCloudChannelPreference('running', storage)
assert.equal(readCloudChannelPreference(storage), 'running')
saveCloudPoolPreference(true, storage)
assert.equal(readCloudChannelPreference(storage), 'running')
saveCloudPoolPreference(false, storage)
const studio = readFileSync(new URL('../src/useStudio.js', import.meta.url), 'utf8')
assert.match(studio, /if\(page==='services'\)w.form.method=readCloudChannelPreference\(\)/)
assert.match(studio, /if\(studioPage.value==='services'\)saveCloudChannelPreference\(method\)/)
assert.match(studio, /if\(!draft\)\{w.form.method=readCloudChannelPreference\(\)/)
assert.equal(readCloudPoolPreference(storage), false)
saveCloudPoolPreference(true, storage)
assert.equal(readCloudPoolPreference(storage), true)
const form = { use_cloud_image_pool: true, project_name: '' }
Object.assign(form, workspaceParameters({ use_cloud_image_pool: false, project_name: '旧任务' }))
assert.equal(form.use_cloud_image_pool, true)
assert.equal(form.project_name, '旧任务')
Object.assign(form, workspaceParameters({ use_cloud_image_pool: false, project_name: '旧预设' }))
assert.equal(form.use_cloud_image_pool, true)
saveCloudPoolPreference(false, storage)
assert.equal(readCloudPoolPreference(storage), false)
assert.equal(readCloudPoolPreference({ getItem() { throw Error('blocked') } }), false)
assert.doesNotThrow(() => saveCloudPoolPreference(true, { setItem() { throw Error('blocked') } }))
const source = readFileSync(new URL('../src/useWorkspace.js', import.meta.url), 'utf8')
assert.match(source, /use_cloud_image_pool: readCloudPoolPreference\(\)/)
assert.match(source, /Object\.entries\(workspaceParameters\(job\.request\)\)/)
assert.match(source, /Object\.assign\(form, workspaceParameters\(parameters\)\)/)
assert.match(source, /saveCloudPoolPreference\(enabled\)/)
// Guided steps must preserve the selected cloud route and require login,
// rather than silently serializing a personal route when authentication expires.
assert.match(source, /function guidedVisualParameters\(\)[\s\S]*?\.\.\.guidedServiceParameters\(form, cloudSession.value.authenticated\)/)
console.log('cloud pool preference regression tests passed')
