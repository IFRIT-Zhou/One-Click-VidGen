const puppeteer=require('../../node_modules/puppeteer-core')
const assert=require('node:assert/strict')
const {spawn}=require('node:child_process')
const path=require('node:path')
const {mkdirSync}=require('node:fs')
;(async()=>{
 const output=path.resolve(__dirname,'../../runtime/temp');mkdirSync(output,{recursive:true})
 const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5184','--strictPort'],{cwd:path.resolve(__dirname,'..'),windowsHide:true,stdio:['ignore','pipe','pipe']})
 let browser
 try{
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('fixture server timeout')),12000);server.stdout.on('data',data=>{if(String(data).includes('Local:')){clearTimeout(timer);resolve()}});server.on('error',reject);server.on('exit',code=>{clearTimeout(timer);reject(Error('fixture exited '+code))})})
  browser=await puppeteer.launch({executablePath:process.argv[2],headless:true,args:['--disable-gpu'],timeout:15000})
  const page=await browser.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.setRequestInterception(true)
  page.on('request',request=>request.url().endsWith('/api/image-profiles')?request.respond({status:200,contentType:'application/json',body:JSON.stringify({profiles:[{id:'own',name:'我的图像接口',model_id:'image-test',configured:true,protocol:'openai_sync',size:'1536x1024',resolutions:['1k','2k']}]})}):request.continue())
  await page.setViewport({width:1200,height:700})
  await page.goto('http://127.0.0.1:5184/tests/project-image-route.html',{waitUntil:'networkidle0'})
  const channel='.project-image-route select'
  assert.match(await page.$eval('header',e=>e.textContent),/ICAN.*GPT Image 2.5.*2560×1440/)
  await page.select(channel,'running');await page.click('#retry')
  await page.waitForFunction(()=>window.fixture.state.calls.length===2)
  assert.deepEqual(await page.evaluate(()=>window.fixture.state.calls.map(c=>c.action)),['save','generate'])
  assert.equal(await page.evaluate(()=>window.fixture.state.calls[1].method),'running')
  assert.equal(await page.evaluate(()=>window.fixture.state.project.shots[0].image),'keep.jpg')
  await page.select(channel,'personal')
  await page.waitForSelector('.project-image-route input[disabled]')
  assert.equal(await page.$eval('.project-image-route input',e=>e.value),'1536x1024')
  await page.click('#retry');await page.waitForFunction(()=>window.fixture.state.calls.length===4)
  assert.equal(await page.evaluate(()=>window.fixture.state.calls[2].image_profile_id),'own')
  await page.evaluate(()=>{window.fixture.state.pending={projectId:'p',selection:{channel:'ican',size:'2048x1152',image_profile_id:'own',image_resolution:'2k'}};window.fixture.state.fail=true})
  await page.waitForFunction(()=>document.querySelector('.project-image-route select').value==='ican')
  await page.click('#retry');await page.waitForFunction(()=>window.fixture.state.calls.length===5)
  assert.equal(await page.evaluate(()=>window.fixture.state.calls.filter(c=>c.action==='generate').length),2)
  assert.match(await page.$eval('.project-image-route',e=>e.textContent),/登录已过期/)
  await page.evaluate(()=>{window.fixture.state.fail=false})
  await page.click('#retry');await page.waitForFunction(()=>window.fixture.state.calls.length===7)
  assert.equal(await page.evaluate(()=>window.fixture.state.project.creation_parameters.method),'ican')
  // A settings handoff for another project cannot affect this project's draft.
  await page.evaluate(()=>{window.fixture.state.pending={projectId:'other',selection:{channel:'running',image_resolution:'4k',size:'2560x1440'}}})
  assert.equal(await page.$eval(channel,e=>e.value),'ican')
  await page.screenshot({path:path.join(output,'project-image-route-desktop.png'),fullPage:true})
  await page.setViewport({width:390,height:700})
  await page.screenshot({path:path.join(output,'project-image-route-mobile.png'),fullPage:true})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true)
  assert.deepEqual(errors,[])
  console.log('Project image route browser regression passed: channel save/retry ordering, API size, failed save, project isolation, mobile layout.')
 }finally{if(browser)await browser.close();server.kill()}
})().catch(error=>{console.error(error);process.exitCode=1})
