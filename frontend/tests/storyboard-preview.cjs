const puppeteer=require('../../node_modules/puppeteer-core')
const assert=require('node:assert/strict')
const {spawn}=require('node:child_process')
const path=require('node:path')
;(async()=>{
 const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5184','--strictPort'],{cwd:path.resolve(__dirname,'..'),windowsHide:true,stdio:['ignore','pipe','pipe']})
 let browser
 try{
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('server timeout')),12000);server.stdout.on('data',d=>{if(String(d).includes('Local:')){clearTimeout(timer);resolve()}});server.on('exit',c=>{clearTimeout(timer);reject(Error('server exit '+c))})})
  browser=await puppeteer.launch({executablePath:process.argv[2],headless:true,args:['--disable-gpu'],timeout:15000})
  const page=await browser.newPage(),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.setViewport({width:1280,height:1000})
  await page.goto('http://127.0.0.1:5184/tests/storyboard-preview.html',{waitUntil:'networkidle0'})
  await page.click('.storyboard-preview-entry')
  await page.waitForSelector('dialog[open] textarea')
  assert.equal(await page.$eval('footer .primary-btn',e=>e.disabled),false,'Motion generation is not a prerequisite')
  assert.equal((await page.$$('textarea')).length,1,'Static shots do not show motion captions')
  assert.equal(await page.$eval('.preview-options select',e=>e.value),'20')
  await page.screenshot({path:'runtime/temp/storyboard-preview-dialog.png',fullPage:true})
  await page.evaluate(()=>{window.fixture.hasDrafts=true})
  assert.equal(await page.$eval('footer .primary-btn',e=>e.disabled),true)
  await page.evaluate(()=>{window.fixture.hasDrafts=false;window.fixture.project.shots[1].image_status='pending'})
  assert.equal(await page.$eval('footer .primary-btn',e=>e.disabled),true)
  await page.evaluate(()=>{window.fixture.project.shots[1].image_status='completed'})
  await page.$eval('textarea',e=>{e.value='本次预览专用动作说明。';e.dispatchEvent(new Event('input',{bubbles:true}))})
  await page.evaluate(()=>{window.fixture.fail=true})
  await page.click('footer .primary-btn')
  await page.waitForSelector('[role="alert"]')
  assert.equal(await page.$eval('textarea',e=>e.value),'本次预览专用动作说明。','Failure retains edited notes')
  await page.evaluate(()=>{window.fixture.fail=false})
  await page.click('footer .primary-btn')
  await page.waitForSelector('.preview-status')
  assert.equal(await page.$eval('footer .primary-btn',e=>e.disabled),true)
  assert.deepEqual(await page.evaluate(()=>JSON.parse(JSON.stringify(window.fixture.calls.filter(c=>c.method==='POST').at(-1).body))),{revision:7,notes:{a:'本次预览专用动作说明。',b:''},subtitles:true,background_transparency:20})
  await page.keyboard.press('Escape')
  await page.waitForSelector('dialog[open]',{hidden:true})
  assert.equal(await page.$eval('.storyboard-preview-entry',e=>e.textContent),'分镜预览合成中…')
  await page.evaluate(()=>{window.fixture.project.storyboard_preview_task={status:'completed',task_id:'task1'};window.fixture.project.storyboard_preview={status:'completed',file:'preview.mp4',task_id:'task1'}})
  await page.click('.storyboard-preview-entry')
  await page.waitForSelector('a[download="分镜预览.mp4"]')
  assert.equal(await page.evaluate(()=>window.fixture.project.status),'image_review')
  await page.setViewport({width:390,height:850})
  assert.equal(await page.$eval('dialog',e=>e.scrollWidth>e.clientWidth+1),false)
  await page.screenshot({path:'runtime/temp/storyboard-preview-mobile.png',fullPage:true})
  assert.deepEqual(errors,[])
  console.log('Storyboard preview UI: notes, pre-motion export, guards, failure recovery, running/close/reopen, download and mobile layout passed')
 }finally{if(browser)await browser.close();server.kill()}
})().catch(e=>{console.error(e);process.exitCode=1})
