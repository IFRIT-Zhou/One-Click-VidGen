const puppeteer=require('../../node_modules/puppeteer-core')
const assert=require('node:assert/strict')
const {spawn}=require('node:child_process')
const path=require('node:path')
const {mkdirSync}=require('node:fs')
;(async()=>{
 const output=path.resolve(__dirname,'../../runtime/temp')
 mkdirSync(output,{recursive:true})
 const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5182','--strictPort'],{cwd:path.resolve(__dirname,'..'),windowsHide:true,stdio:['ignore','pipe','pipe']})
 let browser
 try{
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('fixture server timeout')),12000);server.stdout.on('data',data=>{if(String(data).includes('Local:')){clearTimeout(timer);resolve()}});server.on('error',reject);server.on('exit',code=>{clearTimeout(timer);reject(Error('fixture server exited '+code))})})
  browser=await puppeteer.launch({executablePath:process.argv[2],headless:true,args:['--disable-gpu'],timeout:15000})
  const page=await browser.newPage(),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.setViewport({width:1200,height:950})
  await page.goto('http://127.0.0.1:5182/tests/shot-duration-navigation.html',{waitUntil:'networkidle0'})
  assert.deepEqual(await page.$$eval('.split-required-label',els=>els.map(el=>el.textContent)),['需拆分 · 14.53 秒','需拆分 · 14.65 秒'])
  assert.deepEqual(await page.$$eval('.navigator-split-summary button',els=>els.map(el=>el.textContent)),['第 05 镜 · 14.53 秒','第 07 镜 · 14.65 秒'])
  await page.select('[aria-label="筛选镜头"]','split')
  assert.equal(await page.$$eval('.navigator-list > button',els=>els.length),2)
  await page.select('[aria-label="筛选镜头"]','static')
  await page.click('.navigator-split-summary button:last-child')
  await page.waitForFunction(()=>window.fixture.selected===6)
  assert.equal(await page.$eval('[aria-label="筛选镜头"]',el=>el.value),'all')
  assert.equal(await page.$eval('.navigator-list button[aria-current="true"]',el=>el.dataset.shotIndex),'6')
  await page.waitForFunction(()=>{const item=document.querySelector('.navigator-list button[aria-current="true"]').getBoundingClientRect(),list=document.querySelector('.navigator-list').getBoundingClientRect();return item.top>=list.top-1&&item.bottom<=list.bottom+1})
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
  await page.screenshot({path:path.join(output,'shot-duration-navigation-desktop.png'),fullPage:true})
  await page.setViewport({width:420,height:920})
  await page.click('.navigator-split-summary button:last-child')
  await page.waitForFunction(()=>{const item=document.querySelector('.navigator-list button[aria-current="true"]').getBoundingClientRect(),list=document.querySelector('.navigator-list').getBoundingClientRect();return item.left>=list.left-1&&item.right<=list.right+1})
  assert.equal(await page.$eval('.shot-navigator',el=>el.scrollWidth>el.clientWidth+1),false)
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
  await page.screenshot({path:path.join(output,'shot-duration-navigation-mobile.png'),fullPage:true})
  await page.evaluate(()=>{window.fixture.shots[4].duration=8;window.fixture.shots[6].video_generation_options={backend:'api'}})
  await page.waitForSelector('.navigator-split-summary',{hidden:true})
  assert.equal(await page.$$eval('.split-required-label',els=>els.length),0)
  assert.deepEqual(errors,[])
  console.log('Shot duration badges, filtering, jump links, responsive layout, and resolved markers: passed')
 }finally{if(browser)await browser.close();server.kill()}
})().catch(error=>{console.error(error);process.exit(1)})
