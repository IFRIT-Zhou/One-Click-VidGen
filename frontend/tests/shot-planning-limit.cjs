const puppeteer=require('../../node_modules/puppeteer-core')
const assert=require('node:assert/strict')
const {spawn}=require('node:child_process')
const path=require('node:path')
const {mkdirSync}=require('node:fs')
;(async()=>{
 const output=path.resolve(__dirname,'../../runtime/temp');mkdirSync(output,{recursive:true})
 const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5183','--strictPort'],{cwd:path.resolve(__dirname,'..'),windowsHide:true,stdio:['ignore','pipe','pipe']})
 let browser
 try{
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('fixture server timeout')),12000);server.stdout.on('data',data=>{if(String(data).includes('Local:')){clearTimeout(timer);resolve()}});server.on('error',reject);server.on('exit',code=>{clearTimeout(timer);reject(Error('fixture exited '+code))})})
  browser=await puppeteer.launch({executablePath:process.argv[2],headless:true,args:['--disable-gpu'],timeout:15000})
  const page=await browser.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.setViewport({width:900,height:650})
  await page.goto('http://127.0.0.1:5183/tests/shot-planning-limit.html',{waitUntil:'networkidle0'})
  const field='input[type="number"]',check='input[type="checkbox"]'
  assert.deepEqual(await page.$eval(field,e=>({value:e.value,disabled:e.disabled})),{value:'14',disabled:true})
  await page.click(check)
  await page.$eval(field,e=>{e.value='28';e.dispatchEvent(new Event('input',{bubbles:true}))})
  await page.waitForFunction(()=>window.fixture.form.dynamic_max_shot_duration===28)
  await page.click(check)
  assert.deepEqual(await page.$eval(field,e=>({value:e.value,disabled:e.disabled})),{value:'14',disabled:true})
  assert.equal(await page.evaluate(()=>window.fixture.form.dynamic_max_shot_duration),28)
  await page.click(check)
  assert.deepEqual(await page.$eval(field,e=>({value:e.value,disabled:e.disabled})),{value:'28',disabled:false})
  await page.evaluate(()=>{window.fixture.form.video_generation_backend='api'})
  await page.waitForSelector(check,{hidden:true})
  assert.deepEqual(await page.$eval(field,e=>({value:e.value,disabled:e.disabled})),{value:'28',disabled:false})
  await page.evaluate(()=>{window.fixture.form.video_generation_backend='cloud_h3'})
  await page.waitForSelector(check)
  assert.equal(await page.$eval(check,e=>e.checked),false)
  await page.click(check)
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
  await page.screenshot({path:path.join(output,'shot-planning-limit-desktop.png'),fullPage:true})
  await page.setViewport({width:390,height:700})
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.screenshot({path:path.join(output,'shot-planning-limit-mobile.png'),fullPage:true})
  assert.deepEqual(errors,[])
  console.log('Planning duration: default 14, lock, restore custom value, provider switch, desktop and mobile layout passed')
 }finally{if(browser)await browser.close();server.kill()}
})().catch(error=>{console.error(error);process.exit(1)})
