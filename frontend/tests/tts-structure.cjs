const puppeteer=require('../../node_modules/puppeteer-core')
const assert=require('node:assert/strict')
const {spawn}=require('node:child_process')
const path=require('node:path')
;(async()=>{
 require('node:fs').mkdirSync('runtime/temp',{recursive:true})
 const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','5183','--strictPort'],{cwd:path.resolve(__dirname,'..'),windowsHide:true,stdio:['ignore','pipe','pipe']})
 let browser
 try{
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('server timeout')),12000);server.stdout.on('data',d=>{if(String(d).includes('Local:')){clearTimeout(timer);resolve()}});server.on('exit',c=>{clearTimeout(timer);reject(Error('server exit '+c))})})
  browser=await puppeteer.launch({executablePath:process.argv[2],headless:true,args:['--disable-gpu'],timeout:15000})
  const page=await browser.newPage(),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.setViewport({width:1200,height:900})
  await page.goto('http://127.0.0.1:5183/tests/tts-structure.html',{waitUntil:'networkidle0'})
  await page.click('.tts-structure-controls .remove')
  await page.waitForSelector('.segment-summary')
  assert.equal(await page.evaluate(()=>window.fixture.calls.length),1)
  assert.equal(await page.evaluate(()=>window.fixture.started),0)
  assert.deepEqual(await page.evaluate(()=>JSON.parse(JSON.stringify(window.fixture.calls[0].body.indices))),[2,3])
  await page.screenshot({path:'runtime/temp/tts-structure-delete.png',fullPage:true})
  await page.click('.tts-structure-dialog footer button:last-child')
  await page.waitForSelector('[role="dialog"]',{hidden:true})
  assert.equal(await page.evaluate(()=>window.fixture.started),1)
  assert.equal(await page.evaluate(()=>window.fixture.busy),false)
  await page.click('.tts-structure-controls button:first-child')
  assert.equal(await page.$eval('.insert-position select',e=>e.value),'2')
  await page.select('.insert-position label:last-child select','before')
  await page.type('textarea','新增内容，只生成这一段。')
  await page.setViewport({width:390,height:850})
  assert.equal(await page.$eval('[role="dialog"]',e=>e.scrollWidth>e.clientWidth+1),false)
  await page.screenshot({path:'runtime/temp/tts-structure-insert-mobile.png',fullPage:true})
  await page.click('.tts-structure-dialog footer button:last-child')
  await page.waitForSelector('[role="dialog"]',{hidden:true})
  assert.deepEqual(await page.evaluate(()=>JSON.parse(JSON.stringify(window.fixture.calls.at(-1).body))),{action:'insert',anchor_index:2,position:'before',text:'新增内容，只生成这一段。',expected_revision:7})
  // Unsaved drafts cannot silently move to a newly renumbered sentence.
  await page.evaluate(()=>{window.fixture.hasDrafts=true})
  await page.click('.tts-structure-controls button:first-child')
  assert.equal(await page.$('[role="dialog"]'),null)
  assert.ok((await page.$eval('[role="alert"]',e=>e.textContent)).includes('草稿'))
  await page.evaluate(()=>{window.fixture.hasDrafts=false})
  await page.click('.tts-structure-controls button:first-child')
  await page.type('textarea','保留我的草稿')
  await page.evaluate(()=>{window.fixture.fail=true})
  await page.click('.tts-structure-dialog footer button:last-child')
  await page.waitForSelector('.tts-structure-dialog [role="alert"]')
  assert.equal(await page.$eval('textarea',e=>e.value),'保留我的草稿')
  assert.equal(await page.evaluate(()=>window.fixture.busy),false)
  await page.keyboard.press('Escape')
  await page.waitForSelector('[role="dialog"]',{hidden:true})
  await page.evaluate(()=>{window.fixture.editor.task.status='running'})
  assert.equal(await page.$$eval('.tts-structure-controls button',els=>els.every(e=>e.disabled)),true)
  await page.evaluate(()=>{window.fixture.editor.task.status='idle';window.fixture.editor.structural_edit_available=false})
  await page.waitForSelector('.tts-structure-controls',{hidden:true})
  assert.deepEqual(errors,[])
  console.log('TTS structure UI: deletion confirmation, insertion position, drafts, failure recovery, busy guards and mobile layout passed')
 }finally{if(browser)await browser.close();server.kill()}
})().catch(e=>{console.error(e);process.exitCode=1})
